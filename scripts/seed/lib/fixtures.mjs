const numbered = (list, i) => {
  const round = Math.floor(i / list.length);
  return round ? `${list[i % list.length]} ${round + 1}` : list[i % list.length];
};

export function person(i) {
  const [firstName, lastName] = PEOPLE[i % PEOPLE.length];
  return { firstName, lastName };
}

export const companyName = (i) => numbered(COMPANIES, i);

/** У владельца склады различаются названием: индекс в названии гарантирует уникальность. */
export const warehouseName = (i) => `${WAREHOUSES[i % WAREHOUSES.length]} (${String(i + 1).padStart(2, '0')})`;

export function address(random) {
  return `г. ${random.pick(CITIES)}, ${random.pick(STREETS)}, д. ${random.int(1, 120)}`;
}

export const objectName = (random) => random.pick(OBJECTS);
